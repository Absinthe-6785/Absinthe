import { createWorkerAuthenticator } from './core-worker-auth.mjs';

const issuer = 'https://core-auth-fixture.invalid/auth/v1';
const path = '/qa/auth/account';
const json = (body, status) => Response.json(body, { status, headers: { 'cache-control': 'no-store' } });

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (env.CORE_AUTH_MODE !== 'synthetic-local' || url.origin !== 'http://127.0.0.1:8788'
      || url.pathname !== path || request.method !== 'GET') return json({ detail: 'Not found' }, 404);
    // This entry has no discovery network access or database binding. Its keys are generated by the test.
    try {
      const authenticate = createWorkerAuthenticator({
        issuer, algorithm: env.CORE_AUTH_ALGORITHM,
        fetchJwks: () => new Response(env.CORE_AUTH_FIXTURE_JWKS),
      });
      const result = await authenticate(request);
      if (result.status === 503) return json({ detail: 'Verification unavailable' }, 503);
      if (result.status !== 200 || request.headers.get('X-Core-QA-Expected-Account') !== result.accountId) {
        return json({ detail: 'Unauthorized' }, 401);
      }
      return json({ accountId: result.accountId }, 200);
    } catch {
      return json({ detail: 'Verification unavailable' }, 503);
    }
  },
};
